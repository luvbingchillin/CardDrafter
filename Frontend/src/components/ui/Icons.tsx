export function StatusDot({
  status,
}: {
  status: 'online' | 'offline' | 'waiting' | 'reconnecting';
}) {
  const colorMap = {
    online: 'var(--primary)',
    offline: 'var(--text-tertiary)',
    waiting: 'var(--rarity-rare)',
    reconnecting: 'var(--rarity-mythic)',
  };

  return (
    <span
      style={{
        display: 'inline-block',
        width: 7,
        height: 7,
        borderRadius: '50%',
        backgroundColor: colorMap[status] || 'var(--text-tertiary)',
        flexShrink: 0,
      }}
      aria-hidden="true"
    />
  );
}
